#!/usr/bin/env python3
"""Assemble per-harness agent files from agents/core and adapters/.

  python3 scripts/build_agents.py           # write the outputs
  python3 scripts/build_agents.py --check   # exit 1 if an output is stale
"""
import argparse
import json
import sys
from pathlib import Path

MARKER = "<!-- generated by scripts/build_agents.py; edit agents/core or adapters -->\n"
RULES_CAP = 24000
OPENCODE_FRONTMATTER = (
    "---\n"
    "description: Runs pstack workflows with this fork's spec, plan, debugging, test-first, and evidence methods.\n"
    "mode: primary\n"
    "---\n"
)


def section(root, adapter, title):
    text = (root / "adapters" / adapter).read_text()
    return "\n## Harness: " + title + "\n\n" + text


def build(root):
    root = Path(root)
    core = (root / "agents/core/pstack-workflow.md").read_text()
    if not core.endswith("\n"):
        core += "\n"
    return {
        "agents/pstack-engineer.md": OPENCODE_FRONTMATTER + MARKER + "\n" + core + section(root, "opencode.md", "OpenCode"),
        "antigravity/rules/AGENTS.md": MARKER + "\n" + core + section(root, "antigravity.md", "Antigravity"),
    }


def problems(root, outputs):
    errors = []
    size = len(outputs["antigravity/rules/AGENTS.md"].encode())
    if size >= RULES_CAP:
        errors.append("antigravity/rules/AGENTS.md is %d bytes; Antigravity truncates rules at %d" % (size, RULES_CAP))
    manifest = root / "antigravity/plugin.json"
    if manifest.exists():
        want = json.loads((root / "plugin.json").read_text())["version"]
        have = json.loads(manifest.read_text()).get("version")
        if have != want:
            errors.append("antigravity/plugin.json version %s differs from plugin.json version %s" % (have, want))
    return errors


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--root", default=str(Path(__file__).resolve().parents[1]))
    args = parser.parse_args()
    root = Path(args.root)
    outputs = build(root)
    errors = problems(root, outputs)
    if args.check:
        for rel, text in outputs.items():
            path = root / rel
            if not path.exists() or path.read_text() != text:
                errors.append("stale: %s (run python3 scripts/build_agents.py)" % rel)
    if errors:
        for line in errors:
            print(line, file=sys.stderr)
        return 1
    if not args.check:
        for rel, text in outputs.items():
            path = root / rel
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
