import json
import re
import shutil
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
BUILD = ["scripts/build_agents.py"]
SOURCES = ["agents", "adapters", "antigravity", "examples", "scripts", "plugin.json"]


def run_build(root, *args):
    return subprocess.run(
        [sys.executable, str(root / "scripts/build_agents.py"), *args],
        cwd=root, capture_output=True, text=True,
    )


class TmpRepo(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp())
        for name in SOURCES:
            src = REPO / name
            if src.is_dir():
                shutil.copytree(src, self.tmp / name)
            elif src.exists():
                shutil.copy2(src, self.tmp / name)

    def tearDown(self):
        shutil.rmtree(self.tmp)


class BuildAgents(TmpRepo):
    def test_outputs_current(self):
        result = run_build(REPO, "--check")
        self.assertEqual(result.returncode, 0, result.stderr)

    def test_stale_detected(self):
        core = self.tmp / "agents/core/pstack-workflow.md"
        core.write_text(core.read_text() + "\nstale\n")
        result = run_build(self.tmp, "--check")
        self.assertEqual(result.returncode, 1)
        self.assertIn("agents/pstack-engineer.md", result.stderr)
        self.assertIn("antigravity/rules/AGENTS.md", result.stderr)

    def test_size_cap(self):
        core = self.tmp / "agents/core/pstack-workflow.md"
        core.write_text(core.read_text() + "x" * 24000 + "\n")
        self.assertEqual(run_build(self.tmp).returncode, 1)
        result = run_build(self.tmp, "--check")
        self.assertEqual(result.returncode, 1)
        self.assertIn("24000", result.stderr)

    def test_opencode_frontmatter(self):
        text = (REPO / "agents/pstack-engineer.md").read_text()
        self.assertTrue(text.startswith("---\ndescription: "), text[:80])
        self.assertIn("\nmode: primary\n---\n<!-- generated by scripts/build_agents.py", text)

    def test_antigravity_rules_marker_and_harness(self):
        text = (REPO / "antigravity/rules/AGENTS.md").read_text()
        self.assertTrue(text.startswith("<!-- generated by scripts/build_agents.py"))
        self.assertIn("## Harness: Antigravity", text)
        self.assertNotIn("## Harness: OpenCode", text)
        self.assertLess(len(text.encode()), 24000)

    def test_no_product_tool_names_in_core(self):
        core = (REPO / "agents/core/pstack-workflow.md").read_text()
        for word in ["question tool", "/models", "opencode models", "ask_question"]:
            self.assertNotIn(word, core)


def frontmatter(text):
    match = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not match:
        return {}
    return dict(line.split(": ", 1) for line in match.group(1).splitlines() if ": " in line)


class PluginManifest(TmpRepo):
    def test_plugin_manifest(self):
        manifest = json.loads((REPO / "antigravity/plugin.json").read_text())
        self.assertEqual(set(manifest), {"name", "displayName", "version", "description"})
        self.assertEqual(manifest["name"], "pstack")
        root_version = json.loads((REPO / "plugin.json").read_text())["version"]
        self.assertEqual(manifest["version"], root_version)
        for name in ["plan-review", "execution-resume"]:
            text = (REPO / "antigravity/skills" / name / "SKILL.md").read_text()
            meta = frontmatter(text)
            self.assertEqual(meta.get("name"), name)
            self.assertTrue(meta.get("description"))
            self.assertNotIn("$ARGUMENTS", text)

    def test_version_drift_detected(self):
        path = self.tmp / "antigravity/plugin.json"
        data = json.loads(path.read_text())
        data["version"] = "0.0.0"
        path.write_text(json.dumps(data))
        result = run_build(self.tmp, "--check")
        self.assertEqual(result.returncode, 1)
        self.assertIn("version", result.stderr)


if __name__ == "__main__":
    unittest.main()
